"""The Python locks pin every package by version and hash, wheels only, and reproduce from requirements.in."""

import os
import re
import shlex
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SKILL = REPO / "skills" / "scenario-kinetic-music-video"
LOCKS = SKILL / "assets" / "python"
PLATFORMS = {"macos-arm64": "aarch64-apple-darwin", "linux-x86_64": "x86_64-manylinux_2_28"}
PIN = re.compile(r"^([A-Za-z0-9._-]+)==(\S+)")
HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}")


def name(text):
    return re.sub(r"[-_.]+", "-", text).lower()


def entries(lock):
    """Each requirement in a lock with the hashes on its continuation lines."""
    out, current = [], None
    for line in lock.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            current = None
            continue
        if not line.startswith(" "):
            current = [line.split(" ;")[0].rstrip(" \\"), []]
            out.append(current)
        elif current is not None:
            current[1] += HASH.findall(line)
    return out


def command(lock):
    """The compile command uv recorded in the lock's header."""
    lines = lock.read_text().splitlines()
    assert lines[0].startswith("# This file was autogenerated by uv"), lines[0]
    return lines[1].lstrip("# ").strip()


class PythonLockTest(unittest.TestCase):
    def test_one_lock_per_platform_the_scaffold_selects(self):
        self.assertEqual(sorted(p.stem for p in LOCKS.glob("*.txt")), sorted(PLATFORMS))
        scaffold = (SKILL / "scripts" / "scaffold.sh").read_text()
        for platform in PLATFORMS:
            self.assertIn(f"PY_LOCK={platform} ;;", scaffold)

    def test_every_package_is_pinned_and_hashed(self):
        for platform in PLATFORMS:
            lock = LOCKS / f"{platform}.txt"
            with self.subTest(lock=lock.name):
                found = entries(lock)
                self.assertGreater(len(found), 50)
                for requirement, hashes in found:
                    self.assertRegex(requirement, PIN, "pinned by version, never a URL or VCS ref")
                    self.assertTrue(hashes, f"{requirement} has no hash")
                self.assertNotIn("git+", lock.read_text())

    def test_header_command_is_hashed_wheels_only_and_writes_this_file(self):
        for platform, target in PLATFORMS.items():
            lock = LOCKS / f"{platform}.txt"
            with self.subTest(lock=lock.name):
                args = shlex.split(command(lock))
                self.assertEqual(args[:3], ["uv", "pip", "compile"])
                self.assertEqual(args[args.index("-o") + 1], str(lock.relative_to(REPO)))
                self.assertEqual(args[args.index("--python-platform") + 1], target)
                self.assertEqual(args[args.index("--only-binary") + 1], ":all:")
                for flag in ("--generate-hashes", "--exclude-newer"):
                    self.assertIn(flag, args)

    def test_direct_requirements_keep_their_pins(self):
        direct = {}
        for line in (LOCKS / "requirements.in").read_text().splitlines():
            line = line.split("#")[0].strip()
            if line:
                match = PIN.match(line)
                direct[name(match[1] if match else line)] = match[2] if match else None
        self.assertEqual(direct["beat-this"], "1.1.0")
        for platform in PLATFORMS:
            locked = {name(m[1]): m[2] for m in (PIN.match(r) for r, _ in entries(LOCKS / f"{platform}.txt"))}
            with self.subTest(lock=platform):
                for package, version in direct.items():
                    self.assertIn(package, locked)
                    if version:
                        self.assertEqual(locked[package], version, package)
                self.assertEqual(locked["torch"], locked["torchaudio"], "torchaudio builds against one torch")

    @unittest.skipUnless(os.environ.get("KINETIC_LOCK_RESOLVE") == "1", "set KINETIC_LOCK_RESOLVE=1 to resolve over the network")
    def test_locks_reproduce_from_their_header_command(self):
        uv = shutil.which("uv")
        self.assertIsNotNone(uv, "uv is required to resolve the locks")
        env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "CONDA_PREFIX")}
        for platform in PLATFORMS:
            lock = LOCKS / f"{platform}.txt"
            with self.subTest(lock=lock.name), tempfile.TemporaryDirectory() as tmp:
                args = shlex.split(command(lock))
                out = Path(tmp) / lock.name
                args[args.index("-o") + 1] = str(out)
                subprocess.run([uv, *args[1:], "--custom-compile-command", command(lock), "-q"], cwd=REPO, env=env, check=True)
                self.assertEqual(out.read_text(), lock.read_text())


if __name__ == "__main__":
    unittest.main()
